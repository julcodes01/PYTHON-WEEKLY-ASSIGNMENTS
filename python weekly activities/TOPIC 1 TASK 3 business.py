# Business Purchase System
# This program calculates the total cost of products purchased.

# Business and product details
business_name = "Juliet's Supermarket"
product_name = "Laptop"
product_price = 65000.00
quantity_purchased = 2

# Calculate total purchase cost
total_cost = product_price * quantity_purchased

# Display the information
print(f"Business Name: {business_name}")
print(f"Product Name: {product_name}")
print(f"Quantity Purchased: {quantity_purchased}")
print(f"Price per Item: KSh {product_price:.2f}")
print(f"Total Cost: KSh {total_cost:.2f}")
